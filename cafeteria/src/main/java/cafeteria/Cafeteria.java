package cafeteria;

import java.nio.file.Files;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.io.IOException;


public final class Cafeteria {
    private static final String URL =
            "jdbc:h2:./base_datos/cafeteria;DB_CLOSE_ON_EXIT=FALSE";
    private static final String USUARIO = "sa";
    private static final String CLAVE = "";

    private Cafeteria() {
    }

    public static Connection conectar() throws SQLException {
        try {
            Files.createDirectories(Paths.get("base_datos"));
        } catch (IOException ex) {
            throw new SQLException("No se pudo crear la carpeta base_datos.", ex);
        }
        return DriverManager.getConnection(URL, USUARIO, CLAVE);
    }

    public static void inicializar() throws SQLException {
        String sql = "CREATE TABLE IF NOT EXISTS pedidos ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP, "
                + "subtotal DECIMAL(12,2) NOT NULL, "
                + "descuento DECIMAL(12,2) NOT NULL, "
                + "total_final DECIMAL(12,2) NOT NULL)";
        try (Connection conexion = conectar();
             Statement sentencia = conexion.createStatement()) {
            sentencia.execute(sql);
        }
    }
}
